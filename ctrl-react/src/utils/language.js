const isValidLanguage = (language) => language === 'en' || language === 'uz';

export function getStoredLanguage() {
  try {
    const storedLanguage = window.localStorage.getItem('ctrl-app-language');
    return isValidLanguage(storedLanguage) ? storedLanguage : 'uz';
  } catch (error) {
    console.error('Til sozlamasini o‘qishda xatolik:', error);
    return 'uz';
  }
}

export function saveStoredLanguage(language) {
  if (!isValidLanguage(language)) {
    throw new Error('Noma’lum til.');
  }
  window.localStorage.setItem('ctrl-app-language', language);
}

export function translate(text, language = 'uz') {
  if (language === 'en') return englishTranslations[text] || text;
  if (language === 'uz') return uzbekTranslations[text] || text;
  return text;
}

export function getWeekdays(language = 'uz') {
  const weekdays = ['Dushanba', 'Seshanba', 'Chorshanba', 'Payshanba', 'Juma', 'Shanba', 'Yakshanba'];
  return weekdays.map((day) => translate(day, language));
}
